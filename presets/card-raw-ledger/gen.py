#!/usr/bin/env python3
"""card-raw-ledger: write data.js (every number the card shows, true to this edit) and thumbs/ (one frame per raw take).

The raw takes are the ones in <SRC without its extension>.offsets.json when the source is several takes joined (a
joined file beside its .offsets.json: {"takes": [{"clip", "offset", "seconds"}]}), else the source itself as one take.
For each take: its length, a 4 Hz loudness envelope of its audio (one value per quarter second, 0-1 on a dB scale set
by the shoot's own level), a 9:16 thumbnail from its middle, and the spans the cut kept from it (edit.py KEEP, with
each piece's place on the output timeline from timeline.json). The lines count is the cut's lines (a run of pieces
joined by jump cuts); the final length is timeline.json total.

Run: PY cards/<id>/gen.py <project>        (rerun it whenever the cut changes)
  reads   <project>/edit.py (SRC, KEEP), <project>/timeline.json, the source file (audio, frames)
  writes  cards/<id>/data.js, cards/<id>/thumbs/<take>.jpg
"""
import importlib.util
import json
import os
import subprocess
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
TW, TH = 270, 480                 # a thumbnail (9:16), shown at 39 x 70 px


def label(sec):
    s = int(round(sec))
    return f"{s // 60}:{s % 60:02d}"


def duration(path):
    r = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", path],
                       capture_output=True, text=True, check=True)
    return float(r.stdout.strip())


def main():
    if os.path.exists(os.path.join(HERE, "preset.json")):
        sys.exit(f"{HERE} is the preset library: make an instance (pipeline/preset.py add) and run its copy")
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    project = os.path.abspath(os.path.expanduser(sys.argv[1]))
    spec = importlib.util.spec_from_file_location("edit", os.path.join(project, "edit.py"))
    E = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(E)
    src = E.SRC
    TL = json.load(open(os.path.join(project, "timeline.json")))
    off = os.path.splitext(src)[0] + ".offsets.json"
    if os.path.exists(off):
        takes = [dict(name=os.path.splitext(t["clip"])[0], offset=float(t["offset"]), sec=float(t["seconds"]))
                 for t in json.load(open(off))["takes"]]
    else:
        takes = [dict(name=os.path.splitext(os.path.basename(src))[0], offset=0.0, sec=duration(src))]
    raw = sum(t["sec"] for t in takes)
    # the voice: mono 8 kHz, a quarter-second RMS envelope on a dB scale relative to the shoot's own level (its 99th
    # percentile + 4.8 dB = 1, 42 dB below that = 0): the card's approved look, at any recording level
    pcm = subprocess.run(["ffmpeg", "-v", "error", "-i", src, "-vn", "-ac", "1", "-ar", "8000", "-f", "s16le", "-"],
                         capture_output=True, check=True).stdout
    a = np.frombuffer(pcm, np.int16).astype(np.float32) / 32768.0
    envs = []
    for t in takes:
        seg = a[int(t["offset"] * 8000):int((t["offset"] + t["sec"]) * 8000)]
        n = max(1, int(np.ceil(t["sec"] * 4)))
        bins = np.array_split(seg, n)
        envs.append(np.array([np.sqrt(np.mean(b * b)) if len(b) else 0.0 for b in bins]))
    dbs = [20 * np.log10(np.maximum(e, 1e-6)) for e in envs]
    top = float(np.percentile(np.concatenate(dbs), 99)) + 4.8
    os.makedirs(os.path.join(HERE, "thumbs"), exist_ok=True)
    keep, out = list(E.KEEP), TL["keep"]
    clips = []
    for t, db in zip(takes, dbs):
        thumb = f"thumbs/{t['name']}.jpg"
        mid = t["offset"] + t["sec"] / 2
        subprocess.run(["ffmpeg", "-v", "error", "-y", "-ss", f"{mid:.3f}", "-i", src, "-frames:v", "1", "-vf",
                        f"scale={TW}:{TH}:force_original_aspect_ratio=increase,crop={TW}:{TH}", "-q:v", "4",
                        os.path.join(HERE, thumb)], check=True)
        kept = [[round(k[0] - t["offset"], 3), round(k[1] - t["offset"], 3), round(o["out"], 4)]
                for k, o in zip(keep, out) if t["offset"] <= k[0] < t["offset"] + t["sec"]]
        clips.append(dict(name=t["name"], sec=round(t["sec"], 6), thumb=thumb,
                          wave=[round(float(np.clip((v - (top - 42)) / 42, 0, 1)), 3) for v in db], kept=kept,
                          keptSec=round(sum(k[1] - k[0] for k in kept), 3)))
    lines = 1 + sum(1 for k in range(1, len(out)) if out[k]["picture_out"] - out[k]["out"] > 0.01)
    data = dict(rawSec=round(raw, 3), rawLabel=label(raw), finalSec=TL["total"], finalLabel=label(TL["total"]),
                keptSec=round(TL.get("total_audio", 0), 3), segCount=lines, clipCount=len(takes), clips=clips)
    with open(os.path.join(HERE, "data.js"), "w", encoding="utf-8") as fh:
        fh.write("/* generated by gen.py from the project's own files: real numbers from this edit */\nwindow.EDIT = "
                 + json.dumps(data, separators=(",", ":")) + ";\n")
    print(f"{HERE}/data.js: {len(takes)} takes ({data['rawLabel']} raw) -> {data['finalLabel']}, {lines} lines, "
          f"{sum(len(c['kept']) for c in clips)} kept pieces; thumbs/ {len(takes)} frames")


if __name__ == "__main__":
    main()
